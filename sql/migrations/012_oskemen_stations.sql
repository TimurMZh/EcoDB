CREATE OR REPLACE VIEW eco.vw_sensor_daily AS
SELECT
    (e.point_id * 100000000000
        + r.param_id * 100000000
        + to_char((s.collection_datetime AT TIME ZONE 'UTC')::date, 'YYYYMMDD')::bigint)
                                                                AS objectid,
    e.point_id,
    p.point_code,
    p.name_ru                                                   AS point_name_ru,
    si.site_code,
    p.geom,
    (s.collection_datetime AT TIME ZONE 'UTC')::date            AS day_utc,
    r.param_id,
    pr.param_code,
    pr.name_ru                                                  AS param_name_ru,
    pr.name_en                                                  AS param_name_en,
    COALESCE(min(r.unit), pr.unit)                              AS unit,
    count(*)::integer                                           AS n_obs,
    min(r.result_value)                                         AS min_value,
    avg(r.result_value)                                         AS avg_value,
    max(r.result_value)                                         AS max_value,
    m.temperature_avg,
    m.pressure_avg,
    m.humidity_avg,
    m.wind_speed_avg
FROM eco.results r
JOIN eco.samples s              ON s.sample_id = r.sample_id
JOIN eco.sampling_events e      ON e.event_id = s.event_id
JOIN eco.monitoring_points p    ON p.point_id = e.point_id
JOIN eco.sites si               ON si.site_id = e.site_id
JOIN eco.parameters pr          ON pr.param_id = r.param_id
LEFT JOIN (
    SELECT
        point_id,
        (observed_at AT TIME ZONE 'UTC')::date AS day_utc,
        avg(temperature)    AS temperature_avg,
        avg(pressure)       AS pressure_avg,
        avg(humidity)       AS humidity_avg,
        avg(wind_speed)     AS wind_speed_avg
    FROM eco.meteo_observations
    GROUP BY 1, 2
) m ON m.point_id = e.point_id
   AND m.day_utc = (s.collection_datetime AT TIME ZONE 'UTC')::date
WHERE s.sample_type = 'hourly_sensor'
GROUP BY
    e.point_id, p.point_code, p.name_ru, si.site_code, p.geom,
    (s.collection_datetime AT TIME ZONE 'UTC')::date,
    r.param_id, pr.param_code, pr.name_ru, pr.name_en, pr.unit,
    m.temperature_avg, m.pressure_avg, m.humidity_avg, m.wind_speed_avg,
    (e.point_id * 100000000000
        + r.param_id * 100000000
        + to_char((s.collection_datetime AT TIME ZONE 'UTC')::date, 'YYYYMMDD')::bigint);

COMMENT ON VIEW eco.vw_sensor_daily IS
  'Суточные min/avg/max автостанций (сутки UTC) с средним метео дня. Query Layer: objectid = point×param×YYYYMMDD.';

