SELECT p.param_id, eco.fn_norm_label(a.alias), 'kgmt'
FROM eco.parameters p
JOIN (VALUES
    ('PM25',   'PM2.5'),
    ('PM25',   'PM25'),
    ('PM10',   'PM10'),
    ('PMtot',  'PMtot'),
    ('SO2_UG', 'SO2'),
    ('NO2_UG', 'NO2'),
    ('NO',     'NO'),
    ('CO_UG',  'CO'),
    ('H2S',    'H2S'),
    ('O3',     'O3')
) AS a(param_code, alias) ON a.param_code = p.param_code
WHERE NOT EXISTS (
    SELECT 1
    FROM eco.parameter_aliases pa
    WHERE pa.alias_norm = eco.fn_norm_label(a.alias)
      AND COALESCE(pa.source_system, '') = 'kgmt'
);

CREATE TABLE eco.meteo_observations (
    meteo_id        bigint          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id        bigint          NOT NULL REFERENCES eco.monitoring_points (point_id),
    observed_at     timestamptz     NOT NULL,
    temperature     numeric(8, 2),
    pressure        numeric(10, 2),
    humidity        numeric(8, 2),
    wind_speed      numeric(8, 2),
    wind_direction  numeric(8, 2),
    source_system   text            NOT NULL DEFAULT 'open-meteo-era5',
    created_at      timestamptz     NOT NULL DEFAULT now(),
    updated_at      timestamptz     NOT NULL DEFAULT now(),
    CONSTRAINT uq_meteo_observations_point_time UNIQUE (point_id, observed_at)
);

COMMENT ON TABLE eco.meteo_observations IS
  'Почасовая метеорология Open-Meteo ERA5 в координатах автостанции. '
  'Связь с hourly_sensor в results: meteo.point_id = sampling_events.point_id '
  'AND meteo.observed_at = samples.collection_datetime. '
  'Часы без загрязнителя в results не пишутся; строка метео при этом остаётся.';
COMMENT ON COLUMN eco.meteo_observations.temperature IS '°C, ERA5 temperature_2m.';
COMMENT ON COLUMN eco.meteo_observations.pressure IS 'гПа, ERA5 surface_pressure.';
COMMENT ON COLUMN eco.meteo_observations.humidity IS '%, ERA5 relative_humidity_2m.';
COMMENT ON COLUMN eco.meteo_observations.wind_speed IS 'км/ч, ERA5 wind_speed_10m.';
COMMENT ON COLUMN eco.meteo_observations.wind_direction IS 'градусы, ERA5 wind_direction_10m.';

CREATE INDEX idx_meteo_observations_time
    ON eco.meteo_observations (observed_at);

DROP TRIGGER IF EXISTS trg_meteo_observations_updated_at ON eco.meteo_observations;
CREATE TRIGGER trg_meteo_observations_updated_at
    BEFORE UPDATE ON eco.meteo_observations
    FOR EACH ROW
