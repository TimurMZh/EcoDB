CREATE TABLE eco.staging_lab_import (
    staging_id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code              text        NOT NULL,
    source_file             text,
    source_sheet            text,
    row_no                  integer,
    lab_code                text,
    site_code               text,
    point_code              text,
    sample_code             text,
    media_type              text,
    param_code              text,
    param_name_raw          text,
    collection_date         date,
    collection_datetime     timestamptz,
    result_text             text,
    unit_raw                text,
    pdk_raw                 text,
    year_num                integer,
    quarter_num             integer,
    extra_json              jsonb,
    loaded_at               timestamptz NOT NULL DEFAULT now(),
    processed_at            timestamptz,
    process_error           text,
    CONSTRAINT ck_staging_quarter CHECK (quarter_num IS NULL OR quarter_num BETWEEN 1 AND 4)
