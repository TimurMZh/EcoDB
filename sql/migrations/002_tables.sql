-- ---------------------------------------------------------------------------
-- Пространственные / объектные
-- ---------------------------------------------------------------------------

CREATE TABLE eco.sites (
    site_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_code   text        NOT NULL,
    name_ru     text        NOT NULL,
    name_en     text,
    description text,
    region      text,
    is_active   boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_sites_code UNIQUE (site_code)
);

COMMENT ON TABLE eco.sites IS 'Производственные объекты (площадки) мониторинга.';

CREATE TABLE eco.monitoring_points (
    point_id    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_code  text        NOT NULL,
    site_id     bigint      NOT NULL REFERENCES eco.sites (site_id),
    name_ru     text        NOT NULL,
    name_en     text,
    media_type  text        NOT NULL REFERENCES eco.ref_media_types (media_code),
    point_type  text,
    geom        geometry(Point, 4326),
    elevation_m numeric(10, 2),
    is_active   boolean     NOT NULL DEFAULT true,
    comments    text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_monitoring_points_code UNIQUE (point_code)
);

COMMENT ON TABLE eco.monitoring_points IS
  'Точки наблюдения. geom — WGS84 (EPSG:4326), совместимо с ArcGIS Enterprise.';
COMMENT ON COLUMN eco.monitoring_points.geom IS 'GEOMETRY(Point, 4326), долгота/широта.';
COMMENT ON COLUMN eco.monitoring_points.point_type IS
  'Классификация точки: скважина, граница СЗЗ, водоток и т.п.';

CREATE TABLE eco.point_aliases (
    alias_id        bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id        bigint  NOT NULL REFERENCES eco.monitoring_points (point_id) ON DELETE CASCADE,
    alias_norm      text    NOT NULL,
    source_system   text
);

COMMENT ON TABLE eco.point_aliases IS
  'Синонимы кодов точек (Т-1 / Т.№1 / скважина ФС-1) для сопоставления при ETL.';

-- ---------------------------------------------------------------------------
-- Лаборатории, события, пробы
-- ---------------------------------------------------------------------------

CREATE TABLE eco.laboratories (
    lab_id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_code            text        NOT NULL,
    name_ru             text        NOT NULL,
    name_en             text,
    accreditation_no    text,
    is_active           boolean     NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_laboratories_code UNIQUE (lab_code)
);

COMMENT ON TABLE eco.laboratories IS 'Лаборатории — источники аналитических данных (ЛАБ1, ЛАБ2, ЛАБ3, …).';

CREATE TABLE eco.sampling_events (
    event_id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id         bigint      NOT NULL REFERENCES eco.sites (site_id),
    point_id        bigint      NOT NULL REFERENCES eco.monitoring_points (point_id),
    event_date      date        NOT NULL,
    event_datetime  timestamptz,
    media_type      text        NOT NULL REFERENCES eco.ref_media_types (media_code),
    sampled_by      text,
    comments        text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_sampling_events_point_date UNIQUE (point_id, event_date, media_type)
);

COMMENT ON TABLE eco.sampling_events IS
  'Событие отбора: объект + точка + дата (+ тип среды). Одна запись на совпадение по ТЗ 6.3.';

CREATE TABLE eco.samples (
    sample_id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id                bigint      NOT NULL REFERENCES eco.sampling_events (event_id),
    lab_id                  bigint      REFERENCES eco.laboratories (lab_id),
    sample_code             text,
    sample_type             text,
    collection_datetime     timestamptz,
    received_datetime       timestamptz,
    coc_number              text,
    comments                text,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE eco.samples IS
  'Проба: метаданные отбора, лаборатория, цепочка хранения (CoC).';
COMMENT ON COLUMN eco.samples.coc_number IS 'Номер акта цепочки хранения пробы (Chain of Custody).';
COMMENT ON COLUMN eco.samples.sample_type IS 'Тип пробы: разовая, составная, холостая и т.п.';

-- ---------------------------------------------------------------------------
-- Нормативно-справочные: показатели и ПДК
-- ---------------------------------------------------------------------------

CREATE TABLE eco.parameters (
    param_id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_code      text        NOT NULL,
    name_ru         text        NOT NULL,
    name_en         text,
    cas_rn          text,
    unit            text        NOT NULL,
    media_type      text        REFERENCES eco.ref_media_types (media_code),
    mdl_default     numeric(18, 8),
    group_name      text,
    sort_order      integer     NOT NULL DEFAULT 0,
    is_active       boolean     NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_parameters_code UNIQUE (param_code)
);

COMMENT ON TABLE eco.parameters IS
  'Реестр показателей (RU/EN), каноническая единица измерения и МДО по умолчанию.';
COMMENT ON COLUMN eco.parameters.mdl_default IS
  'Минимально определяемая концентрация (МДО / MDL) метода по умолчанию.';
COMMENT ON COLUMN eco.parameters.media_type IS
  'Основная среда показателя; NULL — применим к нескольким средам.';

CREATE TABLE eco.parameter_aliases (
    alias_id        bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_id        bigint  NOT NULL REFERENCES eco.parameters (param_id) ON DELETE CASCADE,
    alias_norm      text    NOT NULL,
    source_system   text
);

COMMENT ON TABLE eco.parameter_aliases IS
  'Синонимы названий/кодов показателей лабораторий (ПЭК, ALAB, протоколы) для маппинга ETL.';

CREATE TABLE eco.guideline_standards (
    standard_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_code   text        NOT NULL,
    name_ru         text        NOT NULL,
    name_en         text,
    authority       text,
    media_type      text        REFERENCES eco.ref_media_types (media_code),
    is_active       boolean     NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_guideline_standards_code UNIQUE (standard_code)
);

COMMENT ON TABLE eco.guideline_standards IS
  'Нормативные документы / виды нормативов (ПДК м.р. воздуха, ПДК воды и т.д.).';

CREATE TABLE eco.guideline_values (
    gv_id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_id     bigint      NOT NULL REFERENCES eco.guideline_standards (standard_id),
    param_id        bigint      NOT NULL REFERENCES eco.parameters (param_id),
    media_type      text        NOT NULL REFERENCES eco.ref_media_types (media_code),
    comparison_op   text        NOT NULL DEFAULT 'GT',
    limit_value     numeric(18, 8),
    limit_min       numeric(18, 8),
    limit_max       numeric(18, 8),
    unit            text,
    valid_from      date        NOT NULL DEFAULT DATE '1900-01-01',
    valid_to        date,
    comments        text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_guideline_values_op CHECK (comparison_op IN ('GT', 'GTE', 'LT', 'LTE', 'RANGE')),
    CONSTRAINT ck_guideline_values_limit CHECK (
        (comparison_op IN ('GT', 'GTE', 'LT', 'LTE') AND limit_value IS NOT NULL)
        OR (comparison_op = 'RANGE' AND limit_min IS NOT NULL AND limit_max IS NOT NULL)
    ),
    CONSTRAINT ck_guideline_values_period CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT uq_guideline_values UNIQUE (standard_id, param_id, media_type, valid_from)
);

COMMENT ON TABLE eco.guideline_values IS
  'Численные нормативы (ПДК) показателя с периодом действия. «нет ПДК» = отсутствие строки.';
COMMENT ON COLUMN eco.guideline_values.comparison_op IS
  'GT/GTE — превышение верхней границы; LT/LTE — ниже нижней; RANGE — вне интервала (pH).';

-- ---------------------------------------------------------------------------
-- Результаты и превышения
-- ---------------------------------------------------------------------------

CREATE TABLE eco.results (
    result_id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id           bigint      NOT NULL REFERENCES eco.samples (sample_id),
    param_id            bigint      NOT NULL REFERENCES eco.parameters (param_id),
    result_value        numeric(18, 8),
    less_than           boolean     NOT NULL DEFAULT false,
    unit                text,
    mdl                 numeric(18, 8),
    qc_code             char(1)     REFERENCES eco.ref_qc_codes (qc_code),
    lab_method          text,
    analysis_datetime   timestamptz,
    comments            text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_results_sample_param UNIQUE (sample_id, param_id),
    CONSTRAINT ck_results_value CHECK (less_than OR result_value IS NOT NULL)
);

COMMENT ON TABLE eco.results IS
  'Лабораторные результаты. Пара (sample_id, param_id) уникальна; повторная загрузка обновляет запись.';
COMMENT ON COLUMN eco.results.less_than IS
  'TRUE, если исходное значение «ниже предела обнаружения» (<, ≤, не обн.). result_value тогда = МДО.';
COMMENT ON COLUMN eco.results.qc_code IS
  'Код QA/QC. NULL — не определён, подлежит ручной проверке. D и R скрываются во vw_latest_results.';

CREATE TABLE eco.result_exceedances (
    exceedance_id       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id           bigint      NOT NULL REFERENCES eco.results (result_id) ON DELETE CASCADE,
    gv_id               bigint      NOT NULL REFERENCES eco.guideline_values (gv_id),
    standard_id         bigint      NOT NULL REFERENCES eco.guideline_standards (standard_id),
    limit_value_applied numeric(18, 8) NOT NULL,
    ratio               numeric(18, 6) NOT NULL,
    exceedance_pct      numeric(18, 4) NOT NULL,
    detected_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_result_exceedances UNIQUE (result_id, gv_id)
);

COMMENT ON TABLE eco.result_exceedances IS
  'Автоматически выявленные превышения нормативов. Повторный проход не создаёт дублей (unique result_id + gv_id).';
COMMENT ON COLUMN eco.result_exceedances.ratio IS 'Коэффициент превышения: result_value / limit_value.';
COMMENT ON COLUMN eco.result_exceedances.exceedance_pct IS
  'Процент превышения: (result_value − limit) / limit × 100.';

