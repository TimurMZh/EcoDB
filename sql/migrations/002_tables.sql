CREATE TABLE eco.field_measurements (
    measurement_id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id            bigint      NOT NULL REFERENCES eco.monitoring_points (point_id),
    event_id            bigint      REFERENCES eco.sampling_events (event_id),
    param_id            bigint      NOT NULL REFERENCES eco.parameters (param_id),
    measured_datetime   timestamptz NOT NULL,
    result_value        numeric(18, 8) NOT NULL,
    unit                text,
    instrument          text,
    comments            text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE eco.field_measurements IS
  'Полевые измерения (pH, температура, электропроводность, растворённый кислород и др.).';

CREATE TABLE eco.water_levels (
    level_id                    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id                    bigint      NOT NULL REFERENCES eco.monitoring_points (point_id),
    measured_datetime           timestamptz NOT NULL,
    depth_to_water_m            numeric(10, 3),
    water_elevation_m           numeric(10, 3),
    measuring_point_elevation_m numeric(10, 3),
    comments                    text,
    created_at                  timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_water_levels_point_time UNIQUE (point_id, measured_datetime),
    CONSTRAINT ck_water_levels_value CHECK (
        depth_to_water_m IS NOT NULL OR water_elevation_m IS NOT NULL
    )
);

COMMENT ON TABLE eco.water_levels IS 'Уровни подземных вод (глубина до зеркала и/или абсолютная отметка).';

CREATE TABLE eco.attachments (
    attachment_id   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type     text        NOT NULL,
    entity_id       bigint      NOT NULL,
    file_name       text        NOT NULL,
    file_uri        text,
    mime_type       text,
    description     text,
    uploaded_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_attachments_entity CHECK (
        entity_type IN ('site', 'monitoring_point', 'sampling_event', 'sample', 'result', 'laboratory')
    )
);

COMMENT ON TABLE eco.attachments IS
  'Вложения (протоколы PDF и др.), связанные с записью по entity_type + entity_id.';

