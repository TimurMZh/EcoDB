COMMENT ON COLUMN eco.staging_lab_import.process_error IS
  'Причина, по которой строка не загружена в results; processed_at IS NULL — можно повторить.';
COMMENT ON COLUMN eco.staging_lab_import.extra_json IS 'Поля источника, не попавшие в типизированные колонки.';

